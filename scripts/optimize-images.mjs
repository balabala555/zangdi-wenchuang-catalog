// Build-only dependency. Original uploads are never rewritten.
import sharp from 'sharp';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {products} from '../src/data.js';
const root=fileURLToPath(new URL('../',import.meta.url));
const output=path.join(root,'public/images/optimized');
const manifestFile=path.join(root,'src/generated-images.js');
const hash=bytes=>createHash('sha256').update(bytes).digest('hex');
const settings={thumb:240,card:640,detail:1600};
const sources=[...new Set(products.flatMap(p=>[p.image,p.coverImage,...(p.images || []),...Object.values(p.variantImages || {}).flat()]).filter(Boolean))].sort();
let previous={};
try{previous=JSON.parse((await readFile(manifestFile,'utf8')).split('export const optimizedPhotos = ')[1].trim().replace(/;$/,''));}catch{}
await mkdir(output,{recursive:true});
const manifest={};let reused=0;
for(const source of sources){
 if(!/^public\/images\/[a-zA-Z0-9_./-]+\.(png|jpe?g|webp)$/i.test(source) || source.includes('..'))throw new Error('Invalid photo: '+source);
 const original=await readFile(path.join(root,source));
 const signature=hash(Buffer.concat([original,Buffer.from(JSON.stringify({settings,sharp:sharp.versions,mode:'lossless-srgb-v1'}))]));
 const old=previous[source];
 if(old?.signature===signature){
  let valid=true;
  for(const size of Object.keys(settings)){
   try{if(hash(await readFile(path.join(root,old[size].path)))!==old[size].sha256)valid=false;}catch{valid=false;}
  }
  if(valid){manifest[source]=old;reused++;continue;}
 }
 const entry={signature,originalBytes:original.length};
 // Sequential processing bounds CPU and memory, even for a large catalog.
 for(const [size,width] of Object.entries(settings)){
  let bytes=await sharp(original).rotate().resize({width,height:width,fit:'inside',withoutEnlargement:true}).withIccProfile('srgb').webp({lossless:true,effort:4}).toBuffer();
  let extension='webp';
  // Never make a full-size rendition larger than the original upload.
  const originalInfo=await sharp(original).metadata();
  if(size==='detail' && bytes.length>=original.length && Math.max(originalInfo.width,originalInfo.height)<=settings.detail){bytes=original;extension=path.extname(source).slice(1).toLowerCase();}
  const digest=hash(bytes),filename=`${digest.slice(0,24)}-${size}.${extension}`;
  const relative='public/images/optimized/'+filename;
  await writeFile(path.join(root,relative),bytes);
  const metadata=await sharp(bytes).metadata();
  entry[size]={path:relative,width:metadata.width,height:metadata.height,bytes:bytes.length,sha256:digest};
 }
 manifest[source]=entry;
}
const text='// Generated by npm run images; originals remain untouched.\nexport const optimizedPhotos = '+JSON.stringify(manifest,null,2)+';\n';
await writeFile(manifestFile,text);
console.log(`Photos: ${sources.length} originals, ${reused} unchanged entries reused; lossless thumb/card and detail renditions ready.`);
